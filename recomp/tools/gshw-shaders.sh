#!/usr/bin/env bash
# gshw-shaders.sh — compile recomp/rt/hw/*.vert/*.frag to SPIR-V and write
# them as C arrays into recomp/rt/hw/gs_hw_spv.h (committed, so normal builds
# need no shader compiler). Needs tools/vulkan/glslang (see recomp/NOTES.md).
set -euo pipefail
R="$(cd "$(dirname "$0")/../.." && pwd)"
G=${GLSLANG:-$R/tools/vulkan/glslang/bin/glslang}
H=$R/recomp/rt/hw/gs_hw_spv.h
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
echo "/* generated by recomp/tools/gshw-shaders.sh — do not edit */" > "$H"
for s in gs.vert gs.frag blit.vert blit.frag present.frag; do
  n=spv_${s/./_}
  "$G" -V --quiet --vn $n -o "$T/$n.h" "$R/recomp/rt/hw/$s"
  grep -v '^\s*//' "$T/$n.h" | sed "s/^const uint32_t/static const uint32_t/" >> "$H"
done
# gs.frag with the early depth test (pipelines whose depth format lets the rasterizer's depth bound the written one)
"$G" -V --quiet -DEARLY_Z --vn spv_gs_frag_ez -o "$T/ez.h" "$R/recomp/rt/hw/gs.frag"
grep -v '^\s*//' "$T/ez.h" | sed "s/^const uint32_t/static const uint32_t/" >> "$H"
# FSR 3.1 (--filter fsr3): the motion-vector variants of the GS shaders and the passes around the upscaler
"$G" -V --quiet -DMV_PASS --vn spv_mv_vert -o "$T/mvv.h" "$R/recomp/rt/hw/gs.vert"
"$G" -V --quiet -DMV_PASS --vn spv_mv_frag -o "$T/mvf.h" "$R/recomp/rt/hw/gs.frag"
"$G" -V --quiet --vn spv_fsr3_frag -o "$T/f3.h" "$R/recomp/rt/hw/fsr3.frag"
for f in mvv mvf f3; do grep -v '^\s*//' "$T/$f.h" | sed "s/^const uint32_t/static const uint32_t/" >> "$H"; done
echo "wrote $H" >&2
